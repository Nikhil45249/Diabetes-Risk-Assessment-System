"""
FastAPI application for the Diabetes Risk Assessment ML service.

Endpoints
---------
GET  /health      — service & model status
POST /predict     — run the diabetes risk prediction
GET  /model-info  — model metadata and evaluation metrics
"""

import os
from contextlib import asynccontextmanager
from typing import Optional

from dotenv import load_dotenv
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field, field_validator

from src.predict import load_model, predict, get_metadata, is_model_loaded

load_dotenv()

MODEL_PATH = os.getenv("MODEL_PATH", "models/best_model_pipeline.joblib")


# ---------------------------------------------------------------------------
# Lifespan — load model on startup
# ---------------------------------------------------------------------------

@asynccontextmanager
async def lifespan(app: FastAPI):
    """Load the ML model when the server starts."""
    try:
        load_model(MODEL_PATH)
        print(f"[OK] Model loaded from {MODEL_PATH}")
    except FileNotFoundError as exc:
        print(f"[WARNING] Model not found: {exc}. /predict will return 503.")
    yield


# ---------------------------------------------------------------------------
# App
# ---------------------------------------------------------------------------

app = FastAPI(
    title="Diabetes Risk Assessment — ML Service",
    description=(
        "FastAPI service exposing a trained machine-learning pipeline "
        "for diabetes risk estimation. Educational use only."
    ),
    version="1.0.0",
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)


# ---------------------------------------------------------------------------
# Pydantic schemas
# ---------------------------------------------------------------------------

class PredictionRequest(BaseModel):
    age: int = Field(..., ge=1, le=120, description="Age in years")
    gender: str = Field(..., description="Male or Female")
    height_cm: float = Field(..., ge=50, le=300, description="Height in centimetres")
    weight_kg: float = Field(..., ge=10, le=400, description="Weight in kilograms")
    family_history: bool = Field(..., description="Family history of diabetes")
    physical_activity: str = Field(..., description="Low, Medium, or High")
    smoking: bool = Field(default=False)
    alcohol: bool = Field(default=False)
    healthy_diet: bool = Field(default=True)
    frequent_thirst: bool = Field(default=False)
    frequent_urination: bool = Field(default=False)
    fatigue: bool = Field(default=False)
    blurred_vision: bool = Field(default=False)
    slow_wound_healing: bool = Field(default=False)

    @field_validator("gender")
    @classmethod
    def validate_gender(cls, v: str) -> str:
        cleaned = str(v).strip().title()
        if cleaned not in ("Male", "Female"):
            raise ValueError("Gender must be 'Male' or 'Female'.")
        return cleaned

    @field_validator("physical_activity")
    @classmethod
    def validate_activity(cls, v: str) -> str:
        cleaned = str(v).strip().title()
        if cleaned not in ("Low", "Medium", "High"):
            raise ValueError("Physical activity must be 'Low', 'Medium', or 'High'.")
        return cleaned


class PredictionResult(BaseModel):
    risk_level: str
    bmi: float
    probability: Optional[dict] = None


class PredictionResponse(BaseModel):
    success: bool
    prediction: PredictionResult
    disclaimer: str = (
        "This is an educational risk estimate generated by a model trained on "
        "synthetic data. It is NOT a medical diagnosis. Please consult a "
        "qualified healthcare professional for clinical advice."
    )


class HealthResponse(BaseModel):
    status: str
    model_loaded: bool


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------

@app.get("/health", response_model=HealthResponse)
async def health_check():
    return HealthResponse(
        status="healthy",
        model_loaded=is_model_loaded(),
    )


@app.post("/predict", response_model=PredictionResponse)
async def run_prediction(req: PredictionRequest):
    if not is_model_loaded():
        raise HTTPException(
            status_code=503,
            detail="ML model is not available. Train the model first.",
        )

    try:
        result = predict(req.model_dump())
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Prediction failed: {exc}")

    return PredictionResponse(
        success=True,
        prediction=PredictionResult(**result),
    )


@app.get("/model-info")
async def model_info():
    meta = get_metadata()
    return {"success": True, "data": meta}
